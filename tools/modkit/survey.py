"""Index what a roguelike mode needs from the 1.2.1 RomFS: map files, chests and their contents, enemy families, the
GameData flag table. Writes build/modkit/survey/ (game-derived: never commit it).

    .venv-modkit\\Scripts\\python -m tools.modkit.survey [--out DIR] [--merged]

Outputs:
  summary.md          the counts and findings, in prose
  maps.json           every top-level map placement file by area (shrines, Depths, surface, sky, chasms, caves, ...)
                      with its actor count
  chests.json         chest actors (TBox_*), their placements in the decoded maps, the Dynamic keys they carry and
                      the items they hold (Drop__DropActor)
  enemies.json        Enemy_* actor packs grouped by family
  gamedata.json       the GameDataList tables: entries per type, fields, the flags whose name was found
  flag_names.tsv      hash, type and name of every flag named by an identifier found in the RomFS (murmur3_32)
--merged also decodes the Banc/*/Merged files (about 135,000; slow) for the chest and enemy placement counts.
"""
import argparse
import collections
import json
import re
import struct
import sys
import time
from pathlib import Path

from . import byml, sarc
from .romfs import ROOT, RomFS


def murmur3_32(data, seed=0):
    """MurmurHash3 x86 32. GameDataList keys every flag by murmur3_32 of its name, seed 0 (checked: the Enum tables
    store both their value names and these hashes)."""
    c1, c2, h = 0xcc9e2d51, 0x1b873593, seed
    n = len(data) & ~3

    def mix(k):
        k = (k * c1) & 0xFFFFFFFF
        k = ((k << 15) | (k >> 17)) & 0xFFFFFFFF
        return (k * c2) & 0xFFFFFFFF
    for i in range(0, n, 4):
        h ^= mix(struct.unpack_from('<I', data, i)[0])
        h = ((h << 13) | (h >> 19)) & 0xFFFFFFFF
        h = (h * 5 + 0xe6546b64) & 0xFFFFFFFF
    tail = data[n:]
    if tail:
        h ^= mix(int.from_bytes(tail, 'little'))
    h ^= len(data)
    h ^= h >> 16
    h = (h * 0x85ebca6b) & 0xFFFFFFFF
    h ^= h >> 13
    h = (h * 0xc2b2ae35) & 0xFFFFFFFF
    return h ^ (h >> 16)


# Top-level map areas: (name, RomFS path regex). A Banc scene is a pair of files, <name>_Static and <name>_Dynamic.
AREAS = [
    ('shrines (SmallDungeon)', r'Banc/SmallDungeon/Dungeon\d+_(Static|Dynamic)\.bcett\.byml\.zs'),
    ('Depths (MinusField tiles)', r'Banc/MinusField/[A-J]-\d_(Static|Dynamic)\.bcett\.byml\.zs'),
    ('surface (MainField tiles)', r'Banc/MainField/[A-J]-\d_(Static|Dynamic)\.bcett\.byml\.zs'),
    ('sky (MainField/Sky)', r'Banc/MainField/Sky/.*\.bcett\.byml\.zs'),
    ('chasms (MainField/DeepHole)', r'Banc/MainField/DeepHole/.*\.bcett\.byml\.zs'),
    ('caves and wells (MainField/Cave)', r'Banc/MainField/Cave/.*\.bcett\.byml\.zs'),
    ('large dungeons (LargeDungeon + MainField/LargeDungeon)', r'Banc/(MainField/)?LargeDungeon/.*\.bcett\.byml\.zs'),
    ('castle (MainField/Castle)', r'Banc/MainField/Castle/.*\.bcett\.byml\.zs'),
    ('other stages (NormalStage)', r'Banc/NormalStage/.*\.bcett\.byml\.zs'),
    ('boss vehicles (BossVehicle)', r'Banc/BossVehicle/.*\.bcett\.byml\.zs'),
    ('distance view', r'Banc/(MainField|MinusField)/_DistanceView_.*\.bcett\.byml\.zs'),
]


def walk_actors(root):
    """The placement dicts of a map file: root Actors[] (each has Gyaml, Hash, Translate, optional Dynamic, Links)."""
    if isinstance(root, dict):
        return root.get('Actors') or []
    return []


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--game')
    ap.add_argument('--out', type=Path, default=ROOT / 'build/modkit/survey')
    ap.add_argument('--merged', action='store_true', help='also decode the Merged placement files (slow)')
    a = ap.parse_args(argv)
    t0 = time.time()
    r = RomFS(a.game)
    out = a.out
    out.mkdir(parents=True, exist_ok=True)
    files = sorted(r.files)
    md = ['# Roguelike survey of the TotK 1.2.1 RomFS', '',
          f'Generated by `python -m tools.modkit.survey` from {r.game_dir}. Game-derived: stays in build/.', '']

    # ---- maps
    maps, placements = {}, []   # placements: (area, file, actor dict)
    area_of = {}
    for name, rx in AREAS:
        rr = re.compile(rx)
        for p in files:
            if rr.fullmatch(p) and p not in area_of:
                area_of[p] = name
    gyaml_count = collections.Counter()
    for p, area in sorted(area_of.items(), key=lambda kv: kv[0]):
        doc = byml.read(r.read(p))
        actors = walk_actors(doc.root)
        maps.setdefault(area, []).append({'path': p, 'actors': len(actors)})
        for act in actors:
            placements.append((area, p, act))
            gyaml_count[act.get('Gyaml')] += 1
    merged = {}
    for p in files:
        m = re.match(r'Banc/(\w+)/Merged/', p)
        if m:
            merged[m[1]] = merged.get(m[1], 0) + 1
    if a.merged:
        for p in files:
            if '/Merged/' in p and p.endswith('.bcett.byml.zs'):
                for act in walk_actors(byml.read(r.read(p)).root):
                    placements.append(('merged ' + p.split('/')[1], p, act))
                    gyaml_count[act.get('Gyaml')] += 1
    (out / 'maps.json').write_text(json.dumps({'areas': maps, 'merged_files': merged}, indent=1))
    md += ['## Map placement files', '',
           'Each scene is a `_Static` and a `_Dynamic` `.bcett.byml.zs` (BYML; root `Actors[]`, each with `Gyaml` = actor '
           'name, `Hash` u64, `SRTHash`, `Translate`/`Rotate`/`Scale`, optional `Dynamic` parameters, `Links`, `Phive`).', '',
           '| area | files | actors (decoded) |', '|---|---|---|']
    for area, lst in maps.items():
        md.append(f'| {area} | {len(lst)} | {sum(x["actors"] for x in lst):,} |')
    md += ['', 'Merged placement files (not decoded unless --merged): ' +
           ', '.join(f'{k}: {v:,}' for k, v in sorted(merged.items())), '']
    if a.merged:
        mp = [act for area, _, act in placements if area.startswith('merged ')]
        kinds = collections.Counter(str(act.get('Gyaml', '')).split('_')[0] for act in mp)
        md += [f'Decoded {len(mp):,} placements from the Merged files: '
               f'{sum(1 for x in mp if str(x.get("Gyaml", "")).startswith("TBox_"))} chests, '
               f'{sum(1 for x in mp if str(x.get("Gyaml", "")).startswith("Enemy_"))} enemies; by name prefix: ' +
               ', '.join(f'{k} {v:,}' for k, v in kinds.most_common(8)) + '.', '']

    # ---- chests
    tbox_packs = [p for p in files if re.fullmatch(r'Pack/Actor/TBox_\w+\.pack\.zs', p)]
    tbox = [p.split('/')[-1].split('.')[0] for p in tbox_packs]
    chest_places = [(area, p, act) for area, p, act in placements if str(act.get('Gyaml', '')).startswith('TBox_')]
    dyn_keys = collections.Counter()
    drops = collections.Counter()
    by_area = collections.Counter()
    by_type = collections.Counter()
    for area, p, act in chest_places:
        by_area[area] += 1
        by_type[act['Gyaml']] += 1
        for k, v in (act.get('Dynamic') or {}).items():
            dyn_keys[k] += 1
            if k == 'Drop__DropActor':
                drops[v] += 1
    tb_index = byml.read(r.read('Banc/SmallDungeon/DungeonTreasureBox/SmallDungeon.dungeontreasurebox.byml.zs')).root
    shrine_hashes = {}
    for area, p, act in placements:
        if area.startswith('shrines'):
            shrine_hashes[int(act['Hash'])] = (p, act.get('Gyaml'))
    tb_matched = sum(1 for lst in tb_index.values() for h in lst if int(h) in shrine_hashes and
                     str(shrine_hashes[int(h)][1]).startswith('TBox_'))
    tb_total = sum(len(v) for v in tb_index.values())
    (out / 'chests.json').write_text(json.dumps({
        'chest_actors': tbox, 'placements_by_area': by_area, 'placements_by_type': by_type,
        'dynamic_keys': dyn_keys, 'drop_actors': drops.most_common(),
        'shrine_treasure_index': {'file': 'Banc/SmallDungeon/DungeonTreasureBox/SmallDungeon.dungeontreasurebox.byml.zs',
                                  'shrines': len(tb_index), 'hashes': tb_total, 'matching_TBox_placements': tb_matched},
    }, indent=1))
    md += ['## Chests', '',
           f'{len(tbox)} chest actors (`Pack/Actor/TBox_*.pack.zs`): ' + ', '.join(f'`{n}`' for n in tbox) + '.', '',
           f'{len(chest_places):,} chest placements in the decoded maps; by area: ' +
           ', '.join(f'{k} {v:,}' for k, v in by_area.most_common()) + '.', '',
           'A chest\'s contents are a parameter of its placement, not of the actor: the `Dynamic` dict of the placement. '
           'Keys seen on chest placements (count): ' + ', '.join(f'`{k}` {v:,}' for k, v in dyn_keys.most_common(12)) + '.',
           f'{len(drops):,} distinct `Drop__DropActor` values; the most common: ' +
           ', '.join(f'`{k}` {v}' for k, v in drops.most_common(10)) + '.', '',
           f'`Banc/SmallDungeon/DungeonTreasureBox/SmallDungeon.dungeontreasurebox.byml.zs` maps {len(tb_index)} '
           f'shrines to {tb_total} placement hashes (strings of the u64 `Hash`); {tb_matched} of them are TBox_ placements '
           'in the shrine maps decoded here.', '']

    # ---- enemies
    enemies = collections.defaultdict(list)
    for p in files:
        m = re.fullmatch(r'Pack/Actor/(Enemy_([A-Za-z]+)\w*)\.pack\.zs', p)
        if m:
            enemies[m[2]].append(m[1])
    placed = collections.Counter()
    for g, c in gyaml_count.items():
        m = re.match(r'Enemy_([A-Za-z]+)', str(g))
        if m:
            placed[m[1]] += c
    (out / 'enemies.json').write_text(json.dumps({f: {'actors': v, 'placements_decoded': placed.get(f, 0)}
                                                 for f, v in sorted(enemies.items())}, indent=1))
    md += ['## Enemy families', '',
           f'{sum(len(v) for v in enemies.values())} `Pack/Actor/Enemy_*.pack.zs` actors in {len(enemies)} families '
           '(the word after `Enemy_`). Variants per family, and placements in the decoded maps:', '',
           '| family | actors | placements |', '|---|---|---|']
    for f, v in sorted(enemies.items(), key=lambda kv: -len(kv[1])):
        md.append(f'| {f} | {len(v)} | {placed.get(f, 0):,} |')
    md.append('')

    # ---- GameData
    gd_path = 'GameData/GameDataList.Product.110.byml.zs'
    gd_doc = byml.read(r.read(gd_path))
    gd = gd_doc.root
    tables = {t: {'entries': len(v), 'fields': sorted(v[0]) if v and isinstance(v[0], dict) else []}
              for t, v in gd['Data'].items()}
    by_hash = {}
    for t, v in gd['Data'].items():
        if t != 'Bool64bitKey':
            for e in v:
                by_hash[int(e['Hash'])] = t
    # Names: identifiers found in text-bearing files, hashed. Looked in EventFlow, AINB, BYML string tables.
    words = set()
    rx = re.compile(rb'[A-Za-z_][A-Za-z0-9_.]{2,96}')
    for p in files:
        if p.startswith(('Event/EventFlow/', 'Logic/', 'Sequence/', 'AI/')) or p.endswith('.ainb'):
            words.update(m.decode() for m in rx.findall(r.read(p)))
    for p in r.search('RSDB/*') + [p for p in files if p.startswith('Banc/') and '/Merged/' not in p
                                   and p.endswith('.byml.zs') and not p.endswith('.bcett.byml.zs')]:
        words.update(m.decode() for m in rx.findall(r.read(p)))
    for i in range(1000):   # DungeonState.Dungeon000 ... (Enum per shrine)
        words.add(f'DungeonState.Dungeon{i:03d}')
    named = {}
    for w in words:
        h = murmur3_32(w.encode())
        if h in by_hash:
            named[h] = w
    with open(out / 'flag_names.tsv', 'w', encoding='utf-8') as f:
        f.write('# hash\ttype\tname (murmur3_32 of the name, found in the RomFS)\n')
        for h, w in sorted(named.items(), key=lambda kv: (by_hash[kv[0]], kv[1])):
            f.write(f'{h}\t{by_hash[h]}\t{w}\n')
    per_type = collections.Counter(by_hash[h] for h in named)
    shrine_enum = sorted(w for w in named.values() if w.startswith('DungeonState.'))
    # Bool64bitKey: u64 keys. How many equal a placement hash of the decoded maps?
    place_hashes = {int(act['Hash']) for _, _, act in placements if 'Hash' in act}
    b64 = gd['Data']['Bool64bitKey']
    b64_place = sum(1 for e in b64 if int(e['Hash']) in place_hashes)
    b64_upper = collections.Counter(int(e['Hash']) >> 32 for e in b64)
    upper_named = {u: w for w in words if (u := murmur3_32(w.encode())) in b64_upper}
    reset = collections.Counter(e.get('ResetTypeValue') for v in gd['Data'].values() for e in v)
    (out / 'gamedata.json').write_text(json.dumps({
        'file': gd_path, 'big_endian': gd_doc.big_endian, 'metadata': gd['MetaData'], 'tables': tables,
        'named_flags_per_type': per_type, 'shrine_state_enums': shrine_enum,
        'bool64bitkey': {'entries': len(b64), 'equal_to_a_decoded_placement_hash': b64_place,
                         'distinct_upper_32_bits': len(b64_upper), 'upper_named': upper_named},
        'reset_type_values': {str(k): v for k, v in reset.most_common()},
    }, indent=1, default=lambda o: int(o) if isinstance(o, int) else str(o)))
    md += ['## GameData flags', '',
           f'`{gd_path}` is a **big-endian** BYML (`BY`, version 7) with `Data` (one array per type) and `MetaData` '
           '(save layout). Every entry has `Hash` (u32 = murmur3_32 of the flag name, seed 0; Bool64bitKey: u64), '
           '`ResetTypeValue`, `SaveFileIndex`, and `DefaultValue` or `Values`/`RawValues` by type.', '',
           '| type | entries | named here |', '|---|---|---|']
    for t, v in tables.items():
        md.append(f'| {t} | {v["entries"]:,} | {per_type.get(t, 0):,} |')
    md += ['', f'{len(named):,} of {len(by_hash):,} hashed flags named by identifiers found in EventFlow, AINB, RSDB and '
           'Banc side tables (flag_names.tsv). Shrine state: one Enum per shrine, `DungeonState.DungeonNNN` '
           f'({len(shrine_enum)} found).', '',
           f'Bool64bitKey: {len(b64):,} entries with u64 keys; {b64_place:,} equal a placement `Hash` of the maps decoded '
           f'here; {len(b64_upper):,} distinct upper halves, {len(upper_named)} of them named by a found identifier.', '']
    (out / 'summary.md').write_text('\n'.join(md) + f'\n_{time.time() - t0:.0f} s_\n', encoding='utf-8')
    print(f'survey: {out} ({time.time() - t0:.0f} s)')


if __name__ == '__main__':
    sys.exit(main())
